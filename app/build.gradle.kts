// Release signing reads keystore.properties (local, not committed). Without it,
// release builds fall back to the debug key so anyone can build from source.
val keystoreProps = Properties().apply {
  val f = rootProject.file("keystore.properties")
  if (f.exists()) f.inputStream().use { load(it) }
}

android {
  namespace = "com.raj.zcoderemote"
  compileSdk = 37
  defaultConfig {
    applicationId = "com.raj.zcoderemote"
    minSdk = 26
    targetSdk = 37
    versionCode = 2
    versionName = "1.0.0"
  }

  signingConfigs {
    create("release") {
      if (keystoreProps.isNotEmpty()) {
        storeFile = rootProject.file(keystoreProps["storeFile"] as String)
        storePassword = keystoreProps["storePassword"] as String
        keyAlias = keystoreProps["keyAlias"] as String
        keyPassword = keystoreProps["keyPassword"] as String
      }
    }
  }

  buildTypes {
    release {
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = if (keystoreProps.isNotEmpty()) {
        signingConfigs.getByName("release")
      } else {
        signingConfigs.getByName("debug")
      }
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
  }
  buildFeatures {
    compose = true
    aidl = false
    buildConfig = false
    shaders = false
  }

  packaging {
    resources {
      excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
  }
}

